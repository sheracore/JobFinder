export function portrait(id, blink, t = 0) {
  const key = id + (blink ? ':b' : '');
  if (cache[key]) return cache[key];
  const [c, x] = makeCanvas(32, 32);
  const r = (px, py, w, h, col) => { x.fillStyle = col; x.fillRect(px, py, w, h); };
  r(0, 0, 32, 32, '#10131d');
  DRAW[id]?.(r, blink, t);
  cache[key] = c;
  return c;
}
